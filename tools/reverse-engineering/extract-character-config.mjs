/** Extract literal createNPCS constructor options without evaluating shipped JavaScript. */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { repositoryRoot, assetId } from "./asset-inventory.mjs";
const sourceRoot = process.argv[2] ?? path.join(repositoryRoot, "references/messenger/dist");
const source = await readFile(path.join(sourceRoot, "assets/App3D-DwM1eiaC.js"), "utf8");
const region = source.slice(
  source.indexOf("async createNPCS()"),
  source.indexOf("initQuests(){", source.indexOf("async createNPCS()")),
);
if (!region) throw new Error("createNPCS source boundary changed");
const npcDefinitions = [];
for (const match of region.matchAll(/new npc\(this,(\{.*?\})\)\)/g)) {
  let literal = match[1];
  literal = literal.replace(/math\.radians\(([-.\d]+)\)/g, (_, n) =>
    String((Number(n) * Math.PI) / 180),
  );
  literal = literal
    .replace(/([,{])([A-Za-z_$][\w$]*):/g, '$1"$2":')
    .replace(/!0/g, "true")
    .replace(/!1/g, "false")
    .replace(/([:[,])(-?)\.(\d+)/g, "$1$20.$3");
  const settings = JSON.parse(literal);
  const id = `npc.${settings.id}`;
  npcDefinitions.push({
    id,
    label: settings.extraData.name,
    modelAssetId: assetId(`geometries/${settings.modelURL}`),
    bonesAssetId: assetId(`geometries/${settings.bonesURL}`),
    animations: settings.animations.map((file, index) => ({
      id: `${id}.animation.${index}`,
      assetId: assetId(`geometries/${file}`),
      speed: settings.animationsOptions[index].speed,
      loop: true,
      role: ["idle", "talk", "talk-idle", "walk"][index],
    })),
    position: settings.position,
    rotation: settings.rotation,
    dialogue: settings.texts,
    ...(settings.extraData.voice
      ? { voiceAssetId: `audio.dialogues.${settings.extraData.voice}.ogg` }
      : {}),
    ...(settings.curve ? { curveAssetId: assetId(`geometries/${settings.curve}`) } : {}),
    sourceSymbol: "presentScene.createNPCS",
    referenceSettings: settings,
  });
}
if (npcDefinitions.length !== 20)
  throw new Error(`Expected 20 NPC definitions; found ${npcDefinitions.length}`);
const destination = path.join(repositoryRoot, "frontend/engine3d/src/config");
await mkdir(destination, { recursive: true });
await writeFile(
  path.join(destination, "npcs.ts"),
  `// Generated by tools/reverse-engineering/extract-character-config.mjs.\nimport type { CharacterDefinition } from '../types';\nexport const npcDefinitions: readonly CharacterDefinition[] = ${JSON.stringify(npcDefinitions, null, 2)};\n`,
);
console.log({ npcDefinitions: npcDefinitions.length });
