/** Deterministic inventory of every preserved file; no upstream access or downloads.
 * Usage: node tools/reverse-engineering/asset-inventory.mjs [preserved-dist-directory]
 * Default input: references/messenger/dist. */
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
export const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export function assetId(relativePath) {
  return relativePath
    .replace(/^assets\//, "")
    .replaceAll("/", ".")
    .toLowerCase();
}
export function classifyAsset(relativePath) {
  if (relativePath.endsWith(".drc")) return "geometry";
  if (/\.(ktx2|png|avif|jpg|jpeg|webp)$/.test(relativePath)) return "texture";
  if (/\.(ogg|mp3|wav)$/.test(relativePath)) return "audio";
  if (/\.(font|woff2?|ttf)$/.test(relativePath)) return "font";
  if (relativePath.endsWith(".icon")) return "icon";
  if (/\.(wasm)$/.test(relativePath) || /\/libs\//.test(relativePath)) return "codec";
  if (/worker/i.test(relativePath)) return "worker";
  if (/\.m?js$/.test(relativePath)) return "script";
  if (relativePath.endsWith(".css")) return "style";
  return "other";
}
export async function inventory(directory) {
  const files = [];
  async function visit(current) {
    for (const entry of (await readdir(current, { withFileTypes: true })).sort((a, b) =>
      a.name.localeCompare(b.name, "en"),
    )) {
      const absolute = path.join(current, entry.name);
      if (entry.isDirectory()) await visit(absolute);
      else if (entry.isFile()) {
        const relative = path.relative(directory, absolute).replaceAll("\\", "/");
        const bytes = await readFile(absolute);
        files.push({
          id: assetId(relative),
          path: relative.replace(/^assets\//, ""),
          category: classifyAsset(relative),
          bytes: bytes.length,
          sha256: createHash("sha256").update(bytes).digest("hex"),
          provenance: {
            sourceUrl: `https://messenger.abeto.co/${relative}`,
            referencePath: `references/messenger/dist/${relative}`,
            license: "Pending verification; preserved without changing ownership or terms.",
            status: "preserved-local-artifact",
          },
        });
      }
    }
  }
  await visit(directory);
  const ids = files.map((file) => file.id);
  if (new Set(ids).size !== ids.length)
    throw new Error("Duplicate stable asset ID; preserve extensions for colliding filenames.");
  return files;
}
export async function generate(source = path.join(repositoryRoot, "references/messenger/dist")) {
  // Catalog mount contains only assets; the HTML is inventoried separately for preservation.
  const entries = await inventory(source);
  const assets = entries.filter((entry) => !entry.path.endsWith(".html"));
  const destination = path.join(repositoryRoot, "frontend/engine3d/src/assets");
  await mkdir(destination, { recursive: true });
  await mkdir(path.join(repositoryRoot, "docs/analysis"), { recursive: true });
  await writeFile(
    path.join(destination, "catalog.ts"),
    `// Generated by tools/reverse-engineering/asset-inventory.mjs.\nimport type { AssetDefinition } from '../types';\nimport { resolveForCategory, type AthenaAcceptFormats } from './athena-manifest';\nexport const assetCatalog: readonly AssetDefinition[] = ${JSON.stringify(assets, null, 2)};\nexport const assetById: ReadonlyMap<string, AssetDefinition> = new Map(assetCatalog.map(asset => [asset.id, asset]));\n/**\n * URL of a catalog asset. Athena manifest first (no-op unless the athenaAssets flag is on\n * and it is loaded), but only in a format the category's legacy consumer can read (see\n * resolveForCategory); \`accept\` widens that (e.g. ["glb-meshopt"] or "any"). Legacy hits\n * use \`base\`.\n */\nexport function assetUrl(id: string, base = '/assets/athena/', options: { accept?: AthenaAcceptFormats } = {}): string {\n const asset = assetById.get(id);\n if (!asset) throw new Error('Unknown asset: ' + id);\n return resolveForCategory(asset.category, asset.path, options.accept)?.url ?? base.replace(/\\/?$/, '/') + asset.path;\n}\n`,
  );
  await writeFile(
    path.join(repositoryRoot, "docs/analysis/asset-inventory.json"),
    JSON.stringify(
      {
        source: "https://messenger.abeto.co/",
        count: entries.length,
        totalBytes: entries.reduce((sum, item) => sum + item.bytes, 0),
        files: entries,
      },
      null,
      2,
    ) + "\n",
  );
  return { entries: entries.length, assets: assets.length };
}
