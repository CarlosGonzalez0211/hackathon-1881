-- 0501: class material, objectives and milestones (Content owner). Depends on 0001 (profiles)
-- and 0400 (classes, teaches_class, attends_class). Not applied anywhere yet.
-- course_id and topic_id become foreign keys once the curriculum migration (0100) exists; the API
-- validates them against the curriculum catalog until then. All writes go through the API with
-- the service role; updated_at is set by the API.

create table if not exists public.content_materials (
  id uuid primary key default gen_random_uuid(),
  class_id uuid not null references public.classes (id) on delete cascade,
  course_id uuid not null,
  title text not null check (char_length(title) between 1 and 200),
  filename text not null check (char_length(filename) between 1 and 255),
  mime_type text not null check (mime_type in ('application/pdf', 'text/plain', 'text/markdown')),
  byte_size bigint not null check (byte_size between 1 and 20971520),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  storage_path text not null,
  locale text not null default 'es' check (locale in ('en', 'es')),
  status text not null default 'uploaded'
    check (status in ('uploaded', 'extracting', 'chunking', 'embedding', 'ready', 'failed')),
  error_code text check (error_code in (
    'unsupported_type', 'no_extractable_text', 'too_large', 'embedding_failed', 'storage_failed',
    'internal'
  )),
  error_message text check (char_length(error_message) <= 500),
  attempts integer not null default 0 check (attempts >= 0),
  chunks_total integer not null default 0 check (chunks_total between 0 and 2000),
  chunks_embedded integer not null default 0 check (chunks_embedded between 0 and chunks_total),
  -- Retrieval reads only active_generation, so a ready material keeps answering while a new
  -- generation builds or after a rebuild fails.
  active_generation integer check (active_generation > 0),
  building_generation integer check (building_generation > 0),
  curriculum_version integer not null default 1 check (curriculum_version > 0),
  uploaded_by uuid not null references public.profiles (id),
  -- Set when the server has re-hashed the stored object and sniffed its type.
  verified_at timestamptz,
  -- Short lease taken by each bounded processing step (content_claim_material).
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  processed_at timestamptz,
  -- Re-uploading the same file to the same class returns this row instead of a new one.
  unique (class_id, sha256),
  -- Lets children carry class_id with a composite foreign key, so it can never disagree.
  unique (id, class_id),
  check ((status = 'failed') = (error_code is not null))
);

create table if not exists public.content_material_topics (
  material_id uuid not null references public.content_materials (id) on delete cascade,
  topic_id uuid not null,
  primary key (material_id, topic_id)
);

create index if not exists content_material_topics_topic_idx
  on public.content_material_topics (topic_id);

create table if not exists public.content_objectives (
  -- Generated by the client so edits are idempotent upserts.
  id uuid primary key,
  class_id uuid not null references public.classes (id) on delete cascade,
  topic_id uuid not null,
  material_id uuid,
  code text not null check (char_length(code) between 1 and 32),
  statement_es text not null check (char_length(statement_es) between 1 and 1000),
  statement_en text not null check (char_length(statement_en) between 1 and 1000),
  -- Learning concept key (P2), used to answer Learning's retrieval by concept.
  concept_id text check (char_length(concept_id) between 5 and 160),
  position integer not null default 0 check (position >= 0),
  created_by uuid not null references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (id, class_id),
  foreign key (material_id, class_id)
    references public.content_materials (id, class_id) on delete set null (material_id)
);

create unique index if not exists content_objectives_code_idx
  on public.content_objectives (class_id, topic_id, code) where deleted_at is null;

create table if not exists public.content_milestones (
  id uuid primary key,
  class_id uuid not null references public.classes (id) on delete cascade,
  topic_id uuid,
  title_es text not null check (char_length(title_es) between 1 and 1000),
  title_en text not null check (char_length(title_en) between 1 and 1000),
  due_at timestamptz,
  position integer not null default 0 check (position >= 0),
  created_by uuid not null references public.profiles (id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (id, class_id)
);

create index if not exists content_milestones_class_idx on public.content_milestones (class_id);

-- class_id in both composite keys guarantees a milestone only links objectives of its own class.
create table if not exists public.content_milestone_objectives (
  milestone_id uuid not null,
  objective_id uuid not null,
  class_id uuid not null,
  primary key (milestone_id, objective_id),
  foreign key (milestone_id, class_id)
    references public.content_milestones (id, class_id) on delete cascade,
  foreign key (objective_id, class_id)
    references public.content_objectives (id, class_id) on delete cascade
);

alter table public.content_materials enable row level security;
alter table public.content_material_topics enable row level security;
alter table public.content_objectives enable row level security;
alter table public.content_milestones enable row level security;
alter table public.content_milestone_objectives enable row level security;

-- Clients never write; the API uses the service role.
revoke all on public.content_materials, public.content_material_topics,
  public.content_objectives, public.content_milestones, public.content_milestone_objectives
  from anon;
revoke insert, update, delete, truncate, references, trigger
  on public.content_materials, public.content_material_topics,
    public.content_objectives, public.content_milestones, public.content_milestone_objectives
  from authenticated;

-- Materials: the class professor only. Students get materials through the API, which hides
-- storage_path, sha256, errors and the uploader (RLS filters rows, not columns).
drop policy if exists content_materials_select_professor on public.content_materials;
create policy content_materials_select_professor on public.content_materials
  for select to authenticated
  using (public.teaches_class(class_id));

drop policy if exists content_material_topics_select_professor on public.content_material_topics;
create policy content_material_topics_select_professor on public.content_material_topics
  for select to authenticated
  using (exists (
    select 1 from public.content_materials m
    where m.id = material_id and public.teaches_class(m.class_id)
  ));

-- Objectives and milestones carry nothing sensitive: class members read live rows.
drop policy if exists content_objectives_select_members on public.content_objectives;
create policy content_objectives_select_members on public.content_objectives
  for select to authenticated
  using (
    deleted_at is null
    and (public.teaches_class(class_id) or public.attends_class(class_id))
  );

drop policy if exists content_milestones_select_members on public.content_milestones;
create policy content_milestones_select_members on public.content_milestones
  for select to authenticated
  using (
    deleted_at is null
    and (public.teaches_class(class_id) or public.attends_class(class_id))
  );

drop policy if exists content_milestone_objectives_select_members
  on public.content_milestone_objectives;
create policy content_milestone_objectives_select_members on public.content_milestone_objectives
  for select to authenticated
  using (public.teaches_class(class_id) or public.attends_class(class_id));

-- One bounded processing step at a time per material. Returns the claimed row, or nothing when
-- the material is ready, unverified or another step holds a fresh lease. The API clears
-- claimed_at when its step ends; a crashed step's lease expires after p_lease_seconds.
create or replace function public.content_claim_material(
  p_material_id uuid,
  p_lease_seconds integer default 120
) returns setof public.content_materials
language sql volatile set search_path = ''
as $$
  update public.content_materials
  set claimed_at = now(),
      updated_at = now(),
      attempts = attempts + case when status in ('uploaded', 'failed') then 1 else 0 end,
      status = case when status in ('uploaded', 'failed') then 'extracting' else status end,
      error_code = null,
      error_message = null
  where id = p_material_id
    and verified_at is not null
    and status in ('uploaded', 'failed', 'extracting', 'chunking', 'embedding')
    and (claimed_at is null or claimed_at < now() - make_interval(secs => p_lease_seconds))
  returning *
$$;

revoke all on function public.content_claim_material(uuid, integer)
  from public, anon, authenticated;
grant execute on function public.content_claim_material(uuid, integer) to service_role;
